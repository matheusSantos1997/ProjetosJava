package pct_variaveis;

public class TiposVariaveis {

	public static void main(String[] args) {
		
		//tipos variáveis
		
		//tipos inteiros
		int numero1 = 1245;
		short numero2 = 4523;
		byte numero3 = 127;
		long numero4 = 234534445;
        
		//caracter
		
		char valorChar = 'a';
		
		//flutuante
		
		float numero5 = 4.123f;
		double numero6 = 4.565634;
		
		//Booleano
		
		boolean verdadeiro = true;
		boolean falso = false;
		
		//tipos de variáveis não primitivos - são objetos
		
		String frase = "curso java"; //cadeia de caractere
		
		//constantes
		
		final double pi = 3.14; //sempre usa final
		System.out.println(pi);
	}

}
