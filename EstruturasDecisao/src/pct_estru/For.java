package pct_estru;

public class For {

	public static void main(String[] args) {
		//incrementado
		for(int i = 0; i <= 10; i++) {
			System.out.println("Valor: " + i);
		 }
		   System.out.println("-------------------------------");
		
		    //decrementado
		    for(int i = 10; i >= 0; i--) {
			System.out.println("Valor: " + i);
		
		   }

	}

}
